package com.dadacore.lore.identity.members;

import java.sql.Timestamp;
import java.time.Clock;
import java.time.Duration;
import java.time.Instant;
import java.time.temporal.ChronoUnit;
import java.util.Optional;
import java.util.UUID;

import com.dadacore.lore.audit.AuditEntry;
import com.dadacore.lore.audit.AuditLog;
import com.dadacore.lore.identity.account.UserAccount;
import com.dadacore.lore.identity.account.UserAccountRepository;
import com.dadacore.lore.identity.organization.OrganizationRepository;
import com.dadacore.lore.identity.security.PasswordHasher;
import com.dadacore.lore.identity.security.Tokens;
import com.dadacore.lore.shared.ApiException;
import com.dadacore.lore.shared.Checks;
import org.jspecify.annotations.Nullable;
import org.springframework.http.HttpStatus;
import org.springframework.jdbc.core.simple.JdbcClient;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

/**
 * Password reset links, generated by an administrator (or by the {@code reset-password} server
 * command) and passed on to the person through a safe channel: no mail server is needed.
 *
 * <p>A link is valid 24 hours, once. A new link cancels the previous one.
 */
@Service
class PasswordResets {

    static final Duration VALIDITY = Duration.ofHours(24);

    private final JdbcClient jdbc;
    private final UserAccountRepository accounts;
    private final OrganizationRepository organizations;
    private final PasswordHasher hasher;
    private final AuditLog audit;
    private final Clock clock;

    PasswordResets(JdbcClient jdbc, UserAccountRepository accounts, OrganizationRepository organizations,
            PasswordHasher hasher, AuditLog audit, Clock clock) {
        this.jdbc = jdbc;
        this.accounts = accounts;
        this.organizations = organizations;
        this.hasher = hasher;
        this.audit = audit;
        this.clock = clock;
    }

    record CreatedLink(String url, Instant expiresAt) {
    }

    /**
     * @param createdBy null when the link comes from the server command line
     */
    record ResetDetails(String displayName, String email, @Nullable String createdBy, Instant expiresAt,
            int passwordMinLength) {
    }

    record CompletedReset(UUID userId, UUID organizationId, String email, int sessionTimeoutMinutes) {
    }

    @Transactional
    CreatedLink create(UUID organizationId, UserAccount target, UUID createdBy, String ip, String baseUrl) {
        jdbc.sql("""
                update password_reset_token set revoked_at = now()
                where user_id = ? and used_at is null and revoked_at is null
                """)
                .param(target.id())
                .update();
        String token = Tokens.generate();
        // PostgreSQL keeps microseconds: the date returned now is the one read later.
        Instant expiresAt = clock.instant().truncatedTo(ChronoUnit.MICROS).plus(VALIDITY);
        jdbc.sql("insert into password_reset_token (user_id, organization_id, token_hash, created_by, expires_at) values (?, ?, ?, ?, ?)")
                .params(target.id(), organizationId, Tokens.hash(token), createdBy, Timestamp.from(expiresAt))
                .update();
        audit.record(AuditEntry.of(organizationId, createdBy, "member.reset_link_created")
                .resource("account", target.id())
                .ip(ip)
                .detail("name", target.displayName())
                .build());
        return new CreatedLink(baseUrl + "/reset-password#" + token, expiresAt);
    }

    /**
     * Cancels the links not used yet: an account disabled or removed must not get its access back
     * when it is enabled or invited again.
     */
    void revokeAll(UUID userId) {
        jdbc.sql("""
                update password_reset_token set revoked_at = now()
                where user_id = ? and used_at is null and revoked_at is null
                """)
                .param(userId)
                .update();
    }

    ResetDetails inspect(String token) {
        Valid valid = find(token, false).orElseThrow(PasswordResets::invalidLink);
        return new ResetDetails(valid.account().displayName(), valid.account().email(), valid.createdByName(),
                valid.expiresAt(), organizations.settings(valid.organizationId()).passwordMinLength());
    }

    /** Saves the new password and uses up the link. The caller then closes the other sessions. */
    @Transactional
    CompletedReset complete(String token, String password, String ip) {
        Valid valid = find(token, true).orElseThrow(PasswordResets::invalidLink);
        int minLength = organizations.settings(valid.organizationId()).passwordMinLength();
        Checks checks = Checks.start();
        String accepted = checks.password("password", password, minLength);
        checks.orThrow();
        accounts.updatePassword(valid.account().id(), hasher.hash(accepted));
        accounts.recordLogin(valid.account().id(), clock.instant());
        jdbc.sql("update password_reset_token set used_at = now() where id = ?").param(valid.id()).update();
        audit.record(AuditEntry.of(valid.organizationId(), valid.account().id(), "auth.password_reset")
                .resource("account", valid.account().id())
                .ip(ip)
                .build());
        return new CompletedReset(valid.account().id(), valid.organizationId(), valid.account().email(),
                organizations.settings(valid.organizationId()).sessionTimeoutMinutes());
    }

    private Optional<Valid> find(String token, boolean lock) {
        if (token == null || token.isBlank()) {
            return Optional.empty();
        }
        return jdbc.sql("""
                select t.id, t.user_id, t.organization_id, t.expires_at, c.display_name as created_by_name
                from password_reset_token t
                join user_account u on u.id = t.user_id and u.status = 'ACTIVE'
                join membership m on m.user_id = t.user_id and m.organization_id = t.organization_id
                left join user_account c on c.id = t.created_by
                where t.token_hash = ? and t.used_at is null and t.revoked_at is null and t.expires_at > ?
                """ + (lock ? " for update of t" : ""))
                .params(Tokens.hash(token), Timestamp.from(clock.instant()))
                .query((rs, row) -> new Valid(
                        rs.getObject("id", UUID.class),
                        rs.getObject("user_id", UUID.class),
                        rs.getObject("organization_id", UUID.class),
                        rs.getTimestamp("expires_at").toInstant(),
                        rs.getString("created_by_name"),
                        null))
                .optional()
                .flatMap(valid -> accounts.find(valid.userId()).map(valid::withAccount));
    }

    private static ApiException invalidLink() {
        return new ApiException(HttpStatus.NOT_FOUND, "invalid_link");
    }

    private record Valid(UUID id, UUID userId, UUID organizationId, Instant expiresAt, String createdByName,
            UserAccount account) {

        Valid withAccount(UserAccount account) {
            return new Valid(id, userId, organizationId, expiresAt, createdByName, account);
        }
    }
}
