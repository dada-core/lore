/**
 * French typography: a no-break space before the colon and inside guillemets, a narrow no-break
 * space before ; ? ! and %.
 */
export function frenchTypography(text: string): string {
  return text
    .replace(/ :/g, ' :')
    .replace(/ ([;?!%])/g, ' $1')
    .replace(/« /g, '« ')
    .replace(/ »/g, ' »');
}

export const messages: Record<'fr' | 'en', Record<MessageKey, string>> = {
  fr: Object.fromEntries(Object.entries(fr).map(([key, text]) => [key, frenchTypography(text)])) as Record<MessageKey, string>,
  en,
};
