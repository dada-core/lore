/**
 * French typography: a no-break space before the colon and inside guillemets, a narrow no-break
 * space before ; ? ! and %.
 */
export function frenchTypography(text: string): string {
  return text
    .replace(/ :/g, ' :')
    .replace(/ ([;?!%])/g, ' $1')
    .replace(/« /g, '« ')
    .replace(/ »/g, ' »');
}

